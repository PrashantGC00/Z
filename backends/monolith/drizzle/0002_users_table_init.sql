CREATE TABLE "users" (
	"id" text PRIMARY KEY NOT NULL,
	"email" "citext" NOT NULL,
	"username" text NOT NULL,
	"display_name" text NOT NULL,
	"bio" text,
	"location" text,
	"website" text,
	"avatar_media_id" text,
	"cover_media_id" text,
	"verified" boolean DEFAULT false NOT NULL,
	"posts_count" integer DEFAULT 0 NOT NULL,
	"followers_count" integer DEFAULT 0 NOT NULL,
	"following_count" integer DEFAULT 0 NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "users_email_unique" UNIQUE("email"),
	CONSTRAINT "users_username_unique" UNIQUE("username"),
	CONSTRAINT "users_username_length" CHECK (length("users"."username") BETWEEN 3 AND 30),
	CONSTRAINT "users_username_lowercase" CHECK ("users"."username" = lower("users"."username")),
	CONSTRAINT "users_display_name_length" CHECK (length("users"."display_name") BETWEEN 1 AND 60),
	CONSTRAINT "users_bio_length" CHECK ("users"."bio" IS NULL OR length("users"."bio") <= 300),
	CONSTRAINT "users_location_length" CHECK ("users"."location" IS NULL OR length("users"."location") <= 60),
	CONSTRAINT "users_counts_nonnegative" CHECK ("users"."posts_count" >= 0 AND "users"."followers_count" >= 0 AND "users"."following_count" >= 0)
);
