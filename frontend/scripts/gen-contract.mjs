// Reads api/openapi.yaml and emits src/api/contract.gen.ts: every operation with its
// method, path template and per-architecture x-status. The app uses it to gate features
// and to explain which operation is OFFLINE.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const specPath = fileURLToPath(new URL('../../api/openapi.yaml', import.meta.url))
const outPath = fileURLToPath(new URL('../src/api/contract.gen.ts', import.meta.url))
const METHODS = ['get', 'put', 'post', 'patch', 'delete']

const spec = parse(readFileSync(specPath, 'utf8'))
const architectures = Object.keys(spec['x-architectures'] ?? {})
const operations = []

for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method]
    if (!op) continue
    if (!op.operationId) throw new Error(`${method.toUpperCase()} ${path} has no operationId`)
    const status = op['x-status'] ?? {}
    for (const arch of architectures) {
      if (status[arch] !== 'LIVE' && status[arch] !== 'OFFLINE') {
        throw new Error(`${op.operationId}: x-status.${arch} must be LIVE or OFFLINE`)
      }
    }
    operations.push({
      operationId: op.operationId,
      method: method.toUpperCase(),
      path,
      tag: op.tags?.[0] ?? 'Other',
      summary: op.summary ?? '',
      status,
    })
  }
}

const out = `// Generated by scripts/gen-contract.mjs from api/openapi.yaml. Do not edit.
export const ARCHITECTURE_IDS = ${JSON.stringify(architectures)} as const

export const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const
`
writeFileSync(outPath, out)
console.log(`contract: ${operations.length} operations, architectures: ${architectures.join(', ')}`)
